-- 6.1) Registro público de eventos por função, com deduplicação de visitas em 24h.
create or replace function public.registrar_evento_loja(
  p_loja_id bigint, p_tipo text, p_visitante_hash text
) returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  ja_registrado boolean;
begin
  if p_tipo not in ('visita','conversa') then raise exception 'Tipo inválido'; end if;
  if not exists (select 1 from public."Lojas" l where l.id=p_loja_id and l.ativo=true) then
    raise exception 'Loja indisponível';
  end if;
  if p_tipo='visita' then
    if p_visitante_hash is null or length(p_visitante_hash) < 32 or length(p_visitante_hash)>128 then
      raise exception 'Identificador inválido';
    end if;
    perform pg_advisory_xact_lock(hashtextextended(p_loja_id::text || ':' || p_visitante_hash, 0));
    select exists(select 1 from public.loja_eventos e where e.loja_id=p_loja_id
      and e.tipo='visita' and e.visitante_hash=p_visitante_hash
      and e.created_at > now()-interval '24 hours') into ja_registrado;
    if ja_registrado then return false; end if;
  end if;
  insert into public.loja_eventos(loja_id,tipo,visitante_hash)
  values(p_loja_id,p_tipo,p_visitante_hash);
  return true;
end; $$;
revoke all on function public.registrar_evento_loja(bigint,text,text) from public;
grant execute on function public.registrar_evento_loja(bigint,text,text) to anon, authenticated;

-- Eventos só podem ser consultados pelo administrador; gravação via RPC acima.
