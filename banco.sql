-- 4) Eventos para contar visitas/conversas com deduplicação de 24 horas.
create table if not exists public.loja_eventos (
  id bigint generated by default as identity primary key,
  loja_id bigint not null references public."Lojas"(id) on delete cascade,
  tipo text not null check (tipo in ('visita','conversa')),
  visitante_hash text,
  created_at timestamptz not null default now()
);

create index if not exists loja_eventos_loja_data_idx
  on public.loja_eventos (loja_id, created_at desc);

create index if not exists loja_eventos_visitante_idx
  on public.loja_eventos (loja_id, visitante_hash, created_at desc);

-- 5) Função para identificar administradores sem expor permissões ao navegador.
create or replace function public.eh_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users a
    where a.user_id = (select auth.uid())
  );
$$;

revoke all on function public.eh_admin() from public;
grant execute on function public.eh_admin() to anon, authenticated;

